"""Audit saved QVHighlights arrays without modifying data or training a model.

Run: .venv/bin/python eda_dataset.py
"""
import hashlib
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
MODALITIES = ("visual", "speech", "ocr")


def row_hashes(array):
    return [hashlib.sha256(row.tobytes()).hexdigest() for row in array]


def audit(path):
    with np.load(path, allow_pickle=False) as archive:
        arrays = {key: archive[key] for key in archive.files}
    queries, scores, labels = (arrays[k] for k in
                               ("query_embs", "modality_scores", "soft_labels"))
    n = len(queries)
    if queries.shape != (n, 512) or scores.shape != (n, 3) or labels.shape != (n, 3):
        raise ValueError(f"Unexpected dataset shapes in {path}")
    if not all(np.isfinite(a).all() for a in arrays.values()):
        raise ValueError(f"Non-finite values in {path}; repair before class analysis")
    counts = np.bincount(labels.argmax(axis=1), minlength=3)
    hashes = row_hashes(queries)
    full_hashes = row_hashes(np.concatenate([queries, scores, labels], axis=1))
    result = {
        "file": path.name,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "samples": n,
        "arrays": {key: {"shape": list(a.shape), "dtype": str(a.dtype),
                          "nonfinite_values": int((~np.isfinite(a)).sum())}
                   for key, a in arrays.items()},
        "classes": {name: {"count": int(counts[i]),
                            "percent": float(100 * counts[i] / n)}
                    for i, name in enumerate(MODALITIES)},
        "majority_baseline_accuracy": float(counts.max() / n),
        "invalid_soft_label_rows": int(((labels < 0).any(axis=1) |
             ~np.isclose(labels.sum(axis=1), 1, atol=1e-5)).sum()),
        "tied_dominant_label_rows": int(((labels == labels.max(axis=1, keepdims=True)).sum(axis=1) > 1).sum()),
        "score_argmax_label_agreement": float(np.mean(scores.argmax(axis=1) == labels.argmax(axis=1))),
        "duplicate_query_embedding_rows_beyond_first": n - len(set(hashes)),
        "duplicate_complete_rows_beyond_first": n - len(set(full_hashes)),
        "query_norm_range": [float(x) for x in (np.linalg.norm(queries, axis=1).min(),
                                                 np.linalg.norm(queries, axis=1).max())],
        "score_summary": {name: {"min": float(scores[:, i].min()),
                                  "mean": float(scores[:, i].mean()),
                                  "max": float(scores[:, i].max())}
                          for i, name in enumerate(MODALITIES)},
    }
    return result, set(hashes)


def main():
    train, train_hashes = audit(ROOT / "data/qvhighlights_train.npz")
    val, val_hashes = audit(ROOT / "data/qvhighlights_val.npz")
    metadata = json.loads((ROOT / "data/meta_train.json").read_text())
    report = {
        "train": train, "validation": val,
        "shared_exact_query_embeddings": len(train_hashes & val_hashes),
        "training_metadata_rows": len(metadata),
        "limitations": [
            "Classes are argmax of generated soft labels, not human modality annotations.",
            "Score inputs also generate labels; agreement is not retrieval accuracy.",
            "Missing OCR classes cannot be repaired by oversampling absent examples.",
            "Metadata is incomplete; query/video identity leakage cannot be fully audited.",
            "Exact embedding matches are a diagnostic, not proof of identity leakage.",
            "Existing validation was used for checkpoint selection; it is not an independent test set.",
        ],
    }
    out = ROOT / "runs/eda"
    out.mkdir(parents=True, exist_ok=True)
    (out / "dataset_audit.json").write_text(json.dumps(report, indent=2) + "\n")
    lines = ["# QVHighlights dataset EDA", "", "Generated by `eda_dataset.py` from local NPZ files.", "",
             "| Split | Samples | Visual | Speech | OCR | Majority baseline |",
             "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for name, split in (("Train", train), ("Validation", val)):
        cells = [f"{c['count']} ({c['percent']:.2f}%)" for c in split["classes"].values()]
        lines.append(f"| {name} | {split['samples']} | " + " | ".join(cells) +
                     f" | {split['majority_baseline_accuracy']:.2%} |")
    lines += ["", "## Quality checks", ""]
    for name, split in (("Train", train), ("Validation", val)):
        lines.append(f"- {name}: zero non-finite values; {split['invalid_soft_label_rows']} invalid label rows; "
                     f"{split['duplicate_complete_rows_beyond_first']} duplicate complete rows; "
                     f"{split['duplicate_query_embedding_rows_beyond_first']} repeated query embeddings; "
                     f"score-argmax agreement {split['score_argmax_label_agreement']:.2%}.")
    lines += [f"- Shared exact query embeddings across splits: {report['shared_exact_query_embeddings']}.",
              f"- Training metadata: {len(metadata)} rows for {train['samples']} training examples.",
              "", "## Interpretation and next step", ""]
    lines += [f"- {item}" for item in report["limitations"]]
    lines += ["", "Next: recover complete sample identities and define representative, independently annotated "
              "modality/retrieval evaluation data before balancing or tuning. Preserve the current baseline. "
              "Apply any balancing only to training data; log one change per experiment and reserve a final test set."]
    (out / "README.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
